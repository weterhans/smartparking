F_MIN = [3.20,1.28,0.251,0.23,14.6,0.51,0.39,0.14]
F_MAX = [5.46,2.05,0.460,1.03,58.0,0.96,1.00,0.79]
BOBOT = [0.5,2.0,1.0,1.0,1.5,1.2,1.0,1.0]
NAMA  = ["CityCar","Sedan","MPV","SUV","Pickup"]

def norm(f): return [(f[i]-F_MIN[i])/(F_MAX[i]-F_MIN[i]) for i in range(8)]
def wedist(a,b): return math.sqrt(sum(BOBOT[i]*(a[i]-b[i])**2 for i in range(8)))

def predict(fitur, k):
    nu = norm(fitur)
    dists = sorted([(wedist(nu, norm(fl)), lb) for fl,lb in train_data], key=lambda x:x[0])
    nb = [lb for _,lb in dists[:k]]
    return max(set(nb), key=nb.count)

# ─────────────────────────────────────────────────────────────────
# HITUNG CONFUSION MATRIX 5x5
# ─────────────────────────────────────────────────────────────────
def buat_cm(k):
    cm = np.zeros((5,5), dtype=int)
    for (f, lb, _) in test_data:
        pred = predict(f, k)
        cm[lb][pred] += 1
    return cm

# ─────────────────────────────────────────────────────────────────
# PLOT CONFUSION MATRIX
# ─────────────────────────────────────────────────────────────────
def plot_cm(k):
    cm = buat_cm(k)
    total = cm.sum()
    benar = cm.trace()
    akurasi = benar / total * 100

    fig, ax = plt.subplots(figsize=(8, 7))
    fig.patch.set_facecolor('#F8FAFC')
    ax.set_facecolor('#F8FAFC')

    # Colormap hijau (diagonal = benar, merah = salah)
    cmap = LinearSegmentedColormap.from_list(
        'knn_cm', ['#ffffff','#dbeafe','#3b82f6','#1d4ed8'], N=256
    )

    im = ax.imshow(cm, interpolation='nearest', cmap=cmap, vmin=0, vmax=max(cm.max(), 1))

    # Colorbar
    cbar = fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    cbar.ax.tick_params(labelsize=9)
    cbar.set_label('Jumlah Data', fontsize=10)

    # Tick label
    ax.set_xticks(range(5))
    ax.set_yticks(range(5))
    ax.set_xticklabels(NAMA, fontsize=11, fontweight='bold')
    ax.set_yticklabels(NAMA, fontsize=11, fontweight='bold')
    ax.set_xlabel('Prediksi Sistem', fontsize=13, labelpad=12, fontweight='bold')
    ax.set_ylabel('Label Sebenarnya', fontsize=13, labelpad=12, fontweight='bold')
    ax.set_title(
        f'Confusion Matrix — K = {k}\nAkurasi = {benar}/{total} = {akurasi:.2f}%',
        fontsize=14, fontweight='bold', pad=18, color='#1e293b'
    )

    # Isi angka di setiap sel
    thresh = cm.max() / 2.0
    for i in range(5):
        for j in range(5):
            val = cm[i][j]
            color = 'white' if val > thresh else '#1e293b'
            weight = 'bold' if i == j else 'normal'
            ax.text(j, i, str(val),
                    ha='center', va='center',
                    fontsize=15, color=color, fontweight=weight)

    # Kotak merah untuk sel salah klasifikasi
    for i in range(5):
        for j in range(5):
            if i != j and cm[i][j] > 0:
                rect = plt.Rectangle(
                    (j-0.5, i-0.5), 1, 1,
                    linewidth=2.5, edgecolor='#ef4444', facecolor='none'
                )
                ax.add_patch(rect)

    # Kotak hijau untuk diagonal (benar)
    for i in range(5):
        rect = plt.Rectangle(
            (i-0.5, i-0.5), 1, 1,
            linewidth=2.5, edgecolor='#22c55e', facecolor='none'
        )
        ax.add_patch(rect)

    plt.tight_layout()
    fname = f'confusion_matrix_K{k}.png'
    plt.savefig(fname, dpi=150, bbox_inches='tight', facecolor=fig.get_facecolor())
    print(f"Disimpan: {fname}  |  Akurasi K={k}: {akurasi:.2f}%")
    plt.show()

# ─────────────────────────────────────────────────────────────────
# BUAT UNTUK K = 1, 3, 5, 7
# ─────────────────────────────────────────────────────────────────
for k in [1, 3, 5, 7]:
    plot_cm(k)

